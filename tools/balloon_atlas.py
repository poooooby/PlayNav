"""Bake the Balloon Bots' sprites into one indexed atlas (Wilds of Hoenn's colour-number trick).

Every Balloon Bot in data/training_courses.lua (Mega Aggron too) is drawn from the Gen 9 Pack's
battler front sprites (Pokemon Essentials style, 192x192 = 96x96 art doubled; credits in the
pack's credits.txt, "Pokemon Battler Sprites"). Each sprite is halved back to its 96x96 art and
stored as COLOUR NUMBERS: 0 transparent, 1..n an entry of that sprite's own palette (they use
15 colours at most). Out:
  assets/balloon_bots.png   one greyscale column, a 96x96 cell per bot; grey value = number
  data/balloon_bots.lua     the cells and palettes ({ size, cells = { [key] = { row, pal } } },
                            key "<national>" or "<national>-mega", pal = "rrggbbaa" strings)
src/training/arena_draw.lua expands a cell into a full-colour image when its regimen starts.

  python tools/balloon_atlas.py [--pack "<Gen 9 Pack>/Graphics/Pokemon/Front"]
"""
import argparse
import os
import re
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DEFAULT_PACK = os.path.join(os.path.expanduser("~"), "Documents", "GitHub", "1SpriteReferences",
                            "Gen 9 Pack", "Graphics", "Pokemon", "Front")
SIZE = 96

# National Dex number -> the pack's file name (a Mega is "<NAME>_1")
NAMES = {
    3: "VENUSAUR", 6: "CHARIZARD", 9: "BLASTOISE", 72: "TENTACOOL", 73: "TENTACRUEL",
    74: "GEODUDE", 75: "GRAVELER", 76: "GOLEM", 81: "MAGNEMITE", 82: "MAGNETON",
    142: "AERODACTYL", 246: "LARVITAR", 247: "PUPITAR", 248: "TYRANITAR", 304: "ARON", 305: "LAIRON", 306: "AGGRON", 320: "WAILMER",
    321: "WAILORD", 369: "RELICANTH", 407: "ROSERADE", 462: "MAGNEZONE", 475: "GALLADE",
    476: "PROBOPASS", 610: "AXEW", 611: "FRAXURE", 612: "HAXORUS", 618: "STUNFISK",
    633: "DEINO", 634: "ZWEILOUS", 635: "HYDREIGON", 664: "SCATTERBUG", 665: "SPEWPA",
    666: "VIVILLON", 681: "AEGISLASH", 691: "DRAGALGE", 697: "TYRANTRUM", 699: "AURORUS",
    714: "NOIBAT", 715: "NOIVERN",
}


def course_bots():
    """(national, mega) for every bot row in the courses file, in order, once each."""
    src = open(os.path.join(ROOT, "data", "training_courses.lua"), encoding="utf-8").read()
    out, seen = [], set()
    # regular rows: { 320, "SPECIES_WAILMER" } / { 610 } as the bot argument
    for m in re.finditer(r'regular\(\d+, "\w+", "(?:[^"\\]|\\.)*", \{ (\d+)', src):
        key = (int(m.group(1)), False)
        if key not in seen:
            seen.add(key)
            out.append(key)
    for m in re.finditer(r"\{ national = (\d+)([^}]*)\}", src):
        key = (int(m.group(1)), "mega = true" in m.group(2))
        if key not in seen:
            seen.add(key)
            out.append(key)
    return out


def halve(im):
    """The 96x96 art of a doubled sprite: each 2x2 block's first opaque pixel (a lone sliver
    one source pixel wide, as Noivern's wingtip, survives)."""
    w, h = im.size
    src = im.load()
    out = Image.new("RGBA", (w // 2, h // 2), (0, 0, 0, 0))
    dst = out.load()
    for y in range(h // 2):
        for x in range(w // 2):
            pick = (0, 0, 0, 0)
            for dx, dy in ((0, 0), (1, 0), (0, 1), (1, 1)):
                p = src[2 * x + dx, 2 * y + dy]
                if p[3] > 0:
                    pick = p
                    break
            dst[x, y] = pick
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", default=DEFAULT_PACK)
    args = ap.parse_args()

    bots = course_bots()
    atlas = Image.new("L", (SIZE, SIZE * len(bots)), 0)
    cells = []
    for row, (national, mega) in enumerate(bots):
        name = NAMES.get(national)
        if not name:
            sys.exit(f"no pack name for #{national}; add it to NAMES")
        path = os.path.join(args.pack, name + ("_1" if mega else "") + ".png")
        im = Image.open(path).convert("RGBA")
        if im.size == (SIZE * 2, SIZE * 2):
            im = halve(im)
        if im.size != (SIZE, SIZE):
            sys.exit(f"{path}: {im.size}, expected {SIZE * 2} or {SIZE} square")
        pal, index = [], {}
        px = im.load()
        for y in range(SIZE):
            for x in range(SIZE):
                p = px[x, y]
                if p[3] == 0:
                    continue
                if p not in index:
                    pal.append(p)
                    index[p] = len(pal)
                    if len(pal) > 255:
                        sys.exit(f"{path}: more than 255 colours")
                atlas.putpixel((x, row * SIZE + y), index[p])
        key = f"{national}-mega" if mega else str(national)
        cells.append((key, row, pal, name))

    png = os.path.join(ROOT, "assets", "balloon_bots.png")
    atlas.save(png, optimize=True)
    lines = [
        "-- generated by tools/balloon_atlas.py: the Balloon Bots' sprites in assets/balloon_bots.png",
        "-- (one 96x96 cell per bot, grey value = colour number, 0 transparent) and their palettes.",
        "-- Art: the Gen 9 Pack's battler sprites (veekun; Smogon X/Y Sprite Project contributors).",
        "return {",
        f"  size = {SIZE},",
        "  cells = {",
    ]
    for key, row, pal, name in cells:
        hexes = ", ".join('"%02x%02x%02x%02x"' % p for p in pal)
        lines.append(f'    ["{key}"] = {{ row = {row}, pal = {{ {hexes} }} }},  -- {name}')
    lines += ["  },", "}", ""]
    with open(os.path.join(ROOT, "data", "balloon_bots.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(cells)} bots; {png} {os.path.getsize(png)} bytes")


if __name__ == "__main__":
    main()
