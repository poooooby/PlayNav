"""Bake PLAY's lawn (scene/grass) and the grass standing on it (scene/tuft_1..n) from the GRASS+
tile sheet by SciGho (credit in assets/credits.txt) into one indexed atlas (Wilds of Hoenn's
colour-number trick, as tools/decor_atlas.py).

The lawn: one of the sheet's 16-pixel ground tiles (plain green with sparse ticks), each pixel
four units, repeated to the scene's 128 tile and turned to the lawn's bright green, with the
lighter mint oval of the scene laid over it (wrapping, so tiles meet without a seam). The tufts:
the sheet's grass sprites whole inside their cells (a spike of blades, tufts, reeds; the others
are cut flat at a side), turned to the lawn's greens; src/amie/play.lua scatters them over the lawn. The numbers are 16-bit: 0
transparent, 1..n an entry of that picture's own palette. Out:
  assets/amie_grass.png   one 16-bit greyscale image, the pictures packed in a row
  data/amie_grass.lua     { depth = 16, cells = { [id] = { x, y, w, h, pal } } }, "rrggbbaa"

  python tools/play_grass.py "<GRASS+.png>"
"""
import math
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

GROUND = (128, 32)      # the ground tile's corner on the sheet (16 square)
TUFTS = [               # the sheet's grass sprites, those whole inside their cells: x, y, w, h
    (304, 176, 16, 16),    # a small spike of blades
    (320, 176, 16, 16),    # tufts
    (336, 176, 16, 16),
    (256, 192, 16, 16),    # reeds
]
LAWN, LAWN_MINT = (12, 243, 88), (18, 255, 167)
TUFT_DARK, TUFT_LIGHT = (4, 104, 44), (70, 214, 96)


def lum(p):
    return (0.3 * p[0] + 0.59 * p[1] + 0.11 * p[2]) / 255


def lawn(sheet):
    tile = sheet.crop((GROUND[0], GROUND[1], GROUND[0] + 16, GROUND[1] + 16))
    tp = tile.load()
    ls = sorted({lum(tp[x, y]) for y in range(16) for x in range(16)})
    base = ls[len(ls) // 2]
    out = Image.new("RGBA", (128, 128))
    op = out.load()
    for y in range(128):
        for x in range(128):
            # the oval: lighter mint toward the tile's middle, wrapping at its edges
            dx = min(abs(x + 0.5 - 64), 64) / 64
            dy = min(abs(y + 0.5 - 64), 64) / 64
            t = max(0.0, 1 - math.sqrt(dx * dx + dy * dy) * 0.85) ** 0.9
            c = [LAWN[i] + (LAWN_MINT[i] - LAWN[i]) * t for i in range(3)]
            # the tile's marks: a pixel darker or lighter than its middle shades the green
            d = lum(tp[(x // 4) % 16, (y // 4) % 16]) - base
            k = 1 + max(-0.18, min(0.12, d * 1.6))
            op[x, y] = (min(255, round(c[0] * k)), min(255, round(c[1] * k)), min(255, round(c[2] * k)), 255)
    return out


def tuft(sheet, box):
    x, y, w, h = box
    im = sheet.crop((x, y, x + w, y + h))
    px = im.load()
    out = Image.new("RGBA", (w * 4, h * 4))
    for yy in range(h):
        for xx in range(w):
            p = px[xx, yy]
            if p[3] == 0:
                continue
            t = min(1.0, lum(p) * 1.3)
            c = tuple(round(TUFT_DARK[i] + (TUFT_LIGHT[i] - TUFT_DARK[i]) * t) for i in range(3)) + (p[3],)
            for oy in range(4):
                for ox in range(4):
                    out.putpixel((xx * 4 + ox, yy * 4 + oy), c)
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    sheet = Image.open(sys.argv[1]).convert("RGBA")
    pics = [("scene/grass", lawn(sheet))]
    for i, box in enumerate(TUFTS):
        pics.append((f"scene/tuft_{i + 1}", tuft(sheet, box)))
    width = sum(p.size[0] for _, p in pics)
    height = max(p.size[1] for _, p in pics)
    atlas = Image.new("I;16", (width, height), 0)
    rows, ax = [], 0
    for id_, pic in pics:
        px = pic.load()
        pal, index = [], {}
        for y in range(pic.size[1]):
            for x in range(pic.size[0]):
                p = px[x, y]
                if p[3] == 0:
                    continue
                if p not in index:
                    pal.append(p)
                    index[p] = len(pal)
                atlas.putpixel((ax + x, y), index[p])
        rows.append((id_, ax, 0, pic.size[0], pic.size[1], pal))
        ax += pic.size[0]
    png = os.path.join(ROOT, "assets", "amie_grass.png")
    atlas.save(png, optimize=True)
    lines = [
        "-- generated by tools/play_grass.py: PLAY's lawn and its standing grass in assets/amie_grass.png",
        "-- (16-bit grey value = colour number, 0 transparent) and their palettes. Art: see",
        "-- assets/credits.txt (PLAY lawn).",
        "return {",
        "  depth = 16,",
        "  cells = {",
    ]
    for id_, x, y, w, h, pal in rows:
        hexes = ", ".join('"%02x%02x%02x%02x"' % p for p in pal)
        lines.append(f'    ["{id_}"] = {{ x = {x}, y = {y}, w = {w}, h = {h}, pal = {{ {hexes} }} }},')
    lines += ["  },", "}", ""]
    with open(os.path.join(ROOT, "data", "amie_grass.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} pictures; {png} {atlas.size} {os.path.getsize(png)} bytes")


if __name__ == "__main__":
    main()
