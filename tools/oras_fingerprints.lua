-- Write data/oras_fingerprints.lua: the CRC-32 and size of the bytes every
-- recipe row reads from Alpha Sapphire (USA) Rev 2, through the same readers
-- the extract job uses (src/import/ctr.lua, garc.lua, crc32.lua). Hashes only:
-- nothing of the game's content goes into the file. Regenerate whenever
-- data/oras_recipe.lua gains a row from a new place; tools/oras_fingerprints.py
-- checks the result independently.
--
--   luajit tools/oras_fingerprints.lua <alpha_sapphire.cci> > data/oras_fingerprints.lua

local path = arg[1]
if not path then
  io.stderr:write("usage: luajit tools/oras_fingerprints.lua <card image> > data/oras_fingerprints.lua\n")
  os.exit(2)
end

local Ctr = dofile("src/import/ctr.lua")
local Garc = dofile("src/import/garc.lua")
local Crc = dofile("src/import/crc32.lua")
local F = dofile("src/import/fingerprint.lua")
local Recipe = dofile("data/oras_recipe.lua")

local image = assert(io.open(path, "rb"))
local function read(offset, length)
  image:seek("set", offset)
  local s = image:read(length)
  assert(s and #s == length, ("short read at 0x%x"):format(offset))
  return s
end

local fs = assert(Ctr.open(read))
local rows, order, garcs = {}, {}, {}
for _, item in ipairs(Recipe.assets) do
  local key = F.key(item)
  if not rows[key] then
    local off, len = assert(fs:file(item.archive))
    if F.WHOLE[item.kind] then
      rows[key] = { size = len, crc = Crc.ofRange(read, off, len) }
    else
      garcs[item.archive] = garcs[item.archive] or assert(Garc.open(read, off, len))
      local bytes = assert(garcs[item.archive]:bytes(item.entry, item.sub))
      rows[key] = { size = #bytes, crc = Crc.of(bytes) }
    end
    order[#order + 1] = key
  end
end
table.sort(order)

local out = {
  "-- generated by tools/oras_fingerprints.lua: the CRC-32 and size of the bytes each recipe row",
  "-- reads (src/import/fingerprint.lua's keys) in Pokemon Alpha Sapphire (USA) Rev 2. Hashes",
  "-- only; the extract job compares the player's copy against them, row by row.",
  "return {",
  ("  recipe = %d,"):format(Recipe.version),
  "  rows = {",
}
for _, key in ipairs(order) do
  out[#out + 1] = ("    [%q] = { size = %d, crc = %q },"):format(key, rows[key].size, rows[key].crc)
end
out[#out + 1] = "  },"
out[#out + 1] = "}"
io.write(table.concat(out, "\n"), "\n")
io.stderr:write(("%d fingerprints from %d recipe rows\n"):format(#order, #Recipe.assets))
