"""Bake Tile Puzzle's shore trees (tile/trees_day, tile/trees_night) from TREE PIXEL PACK (128) by
AstroCom (https://astrocom.space; credit in assets/credits.txt) into one indexed atlas (Wilds of
Hoenn's colour-number trick, as tools/decor_atlas.py).

The scene (src/amie/games/tile_puzzle.lua, TREES) cuts four pictures out of a 256-square
sheet: a conifer, a round tree, a row of small trees and a bush. This makes that sheet from the
pack's trees, each fitted into its rectangle standing on the rectangle's foot: the spruce, the
oak, three pines side by side and the bush. The night sheet is the day's darkened and turned
blue. The numbers are 16-bit (the shrunken trees keep their soft edges): 0 transparent, 1..n an
entry of that sheet's own palette. Out:
  assets/amie_tile.png   one 16-bit greyscale image, the two sheets side by side
  data/amie_tile.lua     { depth = 16, cells = { [id] = { x, y, w, h, pal } } }, "rrggbbaa"
src/amie/decor_art.lua expands a cell into a full-colour image the first time it is drawn.

  python tools/tile_trees.py "<Tree_Pixel_Pack_128 folder>"
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SIZE = 256

# the scene's rectangles (x, y, w, h) and what fills each: (pack file, how many side by side)
PLACES = [
    ((2, 186, 45, 68), "spruce_summer_1.png", 1),
    ((2, 53, 25, 28), "oak_summer_1.png", 1),
    ((24, 1, 71, 28), "pine_summer_1.png", 3),
    ((116, 209, 40, 41), "bush_summer_1.png", 1),
]
NIGHT = (0.32, 0.4, 0.62)


def trimmed(path):
    im = Image.open(path).convert("RGBA")
    return im.crop(im.getchannel("A").getbbox())


def day_sheet(pack):
    sheet = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    for (x, y, w, h), name, count in PLACES:
        tree = trimmed(os.path.join(pack, name))
        # each tree as tall as the rectangle allows, the row's overlapping a little
        each_w = w / (count * 0.8 + 0.2)
        k = min(h / tree.size[1], each_w / tree.size[0])
        tw, th = max(1, round(tree.size[0] * k)), max(1, round(tree.size[1] * k))
        small = tree.resize((tw, th), Image.LANCZOS)
        for i in range(count):
            cx = x + w / 2 if count == 1 else x + each_w / 2 + i * each_w * 0.8
            sheet.alpha_composite(small, (round(cx - tw / 2), y + h - th))
    return sheet


def night_of(day):
    px = [(round(r * NIGHT[0]), round(g * NIGHT[1]), round(b * NIGHT[2]), a) for r, g, b, a in day.getdata()]
    night = Image.new("RGBA", day.size)
    night.putdata(px)
    return night


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    day = day_sheet(sys.argv[1])
    sheets = [("tile/trees_day", day), ("tile/trees_night", night_of(day))]
    atlas = Image.new("I;16", (SIZE * len(sheets), SIZE), 0)
    rows = []
    for i, (id_, im) in enumerate(sheets):
        px = im.load()
        pal, index = [], {}
        for y in range(SIZE):
            for x in range(SIZE):
                p = px[x, y]
                if p[3] == 0:
                    continue
                if p not in index:
                    pal.append(p)
                    index[p] = len(pal)
                atlas.putpixel((i * SIZE + x, y), index[p])
        rows.append((id_, i * SIZE, 0, pal))
    png = os.path.join(ROOT, "assets", "amie_tile.png")
    atlas.save(png, optimize=True)
    lines = [
        "-- generated by tools/tile_trees.py: Tile Puzzle's shore trees in assets/amie_tile.png",
        "-- (16-bit grey value = colour number, 0 transparent) and their palettes. Art: see",
        "-- assets/credits.txt (Tile Puzzle trees).",
        "return {",
        "  depth = 16,",
        "  cells = {",
    ]
    for id_, ax, ay, pal in rows:
        hexes = ", ".join('"%02x%02x%02x%02x"' % p for p in pal)
        lines.append(f'    ["{id_}"] = {{ x = {ax}, y = {ay}, w = {SIZE}, h = {SIZE}, pal = {{ {hexes} }} }},')
    lines += ["  },", "}", ""]
    with open(os.path.join(ROOT, "data", "amie_tile.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} sheets; {png} {atlas.size} {os.path.getsize(png)} bytes")


if __name__ == "__main__":
    main()
