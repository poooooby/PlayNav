"""Bake PLAY's treeline along the horizon (scene/bushes) from PIXEL BUSHES PACK by AstroCom
(https://astrocom.space; credit in assets/credits.txt) into one indexed atlas (Wilds of Hoenn's
colour-number trick, as tools/decor_atlas.py).

The scene draws a 256 x 128 strip three times across its horizon (src/amie/play.lua): a misty
band of round tree crowns on trunks. This makes it from the pack's bushes: a pale back row of
round bushes, a row of shrubs on their trunks in front, low round and berry bushes along the
foot; each turned to the strip's teal (its light by a dark-to-light ramp), the back row paler
as if further off; its foot cut to a ragged line of undergrowth. src/amie/play.lua sets the strip
in staggered layers, the front one over the lawn's edge. The numbers are 16-bit: 0
transparent, 1..n an entry of that picture's own palette.
Out:
  assets/amie_scene.png   one 16-bit greyscale image
  data/amie_scene.lua     { depth = 16, cells = { [id] = { x, y, w, h, pal } } }, "rrggbbaa"
src/amie/decor_art.lua expands a cell into a full-colour image the first time it is drawn.

  python tools/play_bushes.py "<Pixel_Bushes_Pack/128x128 folder>"
"""
import math
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
W, H = 256, 128

# (pack file, centre x, foot y, height, ramp) back to front
PLACES = [
    ("round_bush_summer_2.png", 40, 92, 78, "far"), ("round_bush_summer_2.png", 118, 84, 84, "far"),
    ("round_bush_summer_2.png", 196, 92, 76, "far"),
    ("shrub_summer_1.png", 24, 124, 104, "near"), ("shrub_summer_2.png", 84, 126, 116, "near"),
    ("shrub_summer_1.png", 150, 125, 110, "near"), ("shrub_summer_2.png", 210, 126, 106, "near"),
    ("round_bush_summer_1.png", 54, 128, 22, "foot"), ("berry_bush_summer_1.png", 120, 128, 20, "foot"),
    ("round_bush_summer_1.png", 180, 128, 22, "foot"), ("berry_bush_summer_1.png", 236, 128, 18, "foot"),
]
# the strip's teal, dark to light, per row
RAMPS = {
    "far": ((40, 150, 130), (130, 236, 196)),
    "near": ((12, 96, 96), (96, 222, 160)),
    "foot": ((10, 78, 86), (40, 150, 126)),
}


def teal(im, ramp):
    (d0, d1, d2), (l0, l1, l2) = RAMPS[ramp]
    out = []
    for r, g, b, a in im.getdata():
        if a == 0:
            out.append((0, 0, 0, 0))
            continue
        t = min(1.0, ((0.3 * r + 0.59 * g + 0.11 * b) / 255) * 1.2)
        out.append((round(d0 + (l0 - d0) * t), round(d1 + (l1 - d1) * t), round(d2 + (l2 - d2) * t), a))
    res = Image.new("RGBA", im.size)
    res.putdata(out)
    return res


def strip(pack):
    band = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    # the shaded undergrowth along the foot, behind the trunks
    px = band.load()
    for x in range(0, 248):
        top = 104 + round(4 * abs(((x * 37) % 23) / 23 - 0.5))
        for y in range(top, H):
            k = (y - top) / max(1, H - top)
            px[x, y] = (round(30 - 14 * k), round(120 - 30 * k), round(116 - 20 * k), 255)
    for name, cx, foot, height, ramp in PLACES:
        im = Image.open(os.path.join(pack, name)).convert("RGBA")
        im = im.crop(im.getchannel("A").getbbox())
        k = height / im.size[1]
        im = im.resize((max(1, round(im.size[0] * k)), height), Image.LANCZOS)
        band.alpha_composite(teal(im, ramp), (round(cx - im.size[0] / 2), foot - height))
    return band


def ragged(band):
    """The strip's foot cut to a ragged line (rounded bumps of undergrowth), not a straight one."""
    px = band.load()
    for x in range(W):
        cut = H - 1 - round(3 + 3 * abs(math.sin(x * 0.16)) + 2 * math.sin(x * 0.41))
        for y in range(cut, H):
            px[x, y] = (0, 0, 0, 0)
    return band


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    pics = [("scene/bushes", ragged(strip(sys.argv[1])))]
    width = sum(p.size[0] for _, p in pics)
    atlas = Image.new("I;16", (width, H), 0)
    cells, ax = [], 0
    for id_, pic in pics:
        px = pic.load()
        pal, index = [], {}
        for y in range(pic.size[1]):
            for x in range(pic.size[0]):
                p = px[x, y]
                if p[3] == 0:
                    continue
                if p not in index:
                    pal.append(p)
                    index[p] = len(pal)
                atlas.putpixel((ax + x, y), index[p])
        cells.append((id_, ax, pic.size[0], pic.size[1], pal))
        ax += pic.size[0]
    png = os.path.join(ROOT, "assets", "amie_scene.png")
    atlas.save(png, optimize=True)
    lines = [
        "-- generated by tools/play_bushes.py: PLAY's treeline in assets/amie_scene.png (16-bit grey",
        "-- value = colour number, 0 transparent) and its palette. Art: see assets/credits.txt",
        "-- (PLAY treeline).",
        "return {",
        "  depth = 16,",
        "  cells = {",
    ]
    for id_, x, w, h, pal in cells:
        hexes = ", ".join('"%02x%02x%02x%02x"' % p for p in pal)
        lines.append(f'    ["{id_}"] = {{ x = {x}, y = 0, w = {w}, h = {h}, pal = {{ {hexes} }} }},')
    lines += ["  },", "}", ""]
    with open(os.path.join(ROOT, "data", "amie_scene.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(cells)} pictures; {png} {atlas.size} {os.path.getsize(png)} bytes")


if __name__ == "__main__":
    main()
