"""Amie PLAY's camera per species from Alpha Sapphire's RomFS -> data/amie_cameras.lua (numbers only).

usage: python tools/amie_cameras.py <romfs-dir> > data/amie_cameras.lua

a/0/8/9 holds Amie's script (entry 0) and a 492-byte record per species (entries 1..721 by
National Dex number; later entries are forms, and the 32-byte ones carry no camera). At 0xB0 a
record holds ten presets of (camera x, y, z, interest x, y, z) as s16 in the PLAY stage's units
(a/1/0/1 entry 0: the Pokemon stands at the origin, y up, the camera on +z). The script's
p_CameraMode picks one: on entering PLAY the average of presets 0 and 1, then 1 while playing,
mode 10 the average of 1 and 2. Presets 0..3 are kept.
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import garc_dump as g  # noqa: E402

KEEP = 4


def main(argv):
    if len(argv) < 1:
        print(__doc__)
        return 2
    data = open(os.path.join(argv[0], 'a', '0', '8', '9'), 'rb').read()
    _, off, entries = g.parse_garc(data)
    rows = []
    for k in range(1, min(len(entries), 722)):
        j, s, e, _ = entries[k][0]
        rec = data[off + s: off + e]   # (stored plain: a first byte 0x10 is data, not LZ)
        if len(rec) < 0xB0 + 12 * KEEP:
            continue
        nums = struct.unpack_from('<%dh' % (6 * KEEP), rec, 0xB0)
        rows.append('  [%d] = { %s },' % (k, ', '.join(str(v) for v in nums)))
    print('-- generated by tools/amie_cameras.py from Alpha Sapphire a/0/8/9 (Amie\'s per-species records,')
    print('-- 0xB0): PLAY\'s camera presets 0..%d per National Dex number, each camera x, y, z then' % (KEEP - 1))
    print('-- interest x, y, z in the stage\'s units (the Pokemon at the origin, y up, the camera on +z).')
    print('-- Numbers only.')
    print('return {')
    print('  presets = %d,' % KEEP)
    print('\n'.join(rows))
    print('}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
