-- luajit tools/lyt_data.lua <cache lyt dir> <out dir> <pack> [<pack> ...]
-- Writes data/lyt/<pack>.lua for each pack: the layouts (.bclyt) and clips (.bclan) the
-- extract copied, parsed by src/lytfile.lua and kept as numbers (pane tree, sizes, colours,
-- materials' texture names, groups, keyframes), so a screen plays without the card image's
-- files. Text panes keep no words (the games set their own). src/lytscreen.lua reads them.

local here = arg[0]:match("^(.*)[/\\]tools[/\\]") or "."
local F = dofile(here .. "/src/lytfile.lua")

local inDir, outDir = arg[1], arg[2]
if not (inDir and outDir and arg[3]) then
  io.stderr:write("usage: luajit tools/lyt_data.lua <cache lyt dir> <out dir> <pack> ...\n")
  os.exit(1)
end

local function readFile(p)
  local f = io.open(p, "rb")
  if not f then return nil end
  local s = f:read("*a")
  f:close()
  return s
end

local function num(v)
  if v == math.floor(v) and math.abs(v) < 1e15 then return ("%d"):format(v) end
  local s = ("%.7g"):format(v)
  return s
end

local KEYWORD = {}
for w in ("and break do else elseif end false for function goto if in local nil not or repeat return then true until while"):gmatch("%a+") do
  KEYWORD[w] = true
end

-- a plain value as Lua source; tables by array part then sorted keys; skips the keys in skip
local function ser(v, skip, out)
  local t = type(v)
  if t == "number" then out[#out + 1] = num(v)
  elseif t == "string" then out[#out + 1] = ("%q"):format(v)
  elseif t == "boolean" then out[#out + 1] = tostring(v)
  elseif t == "table" then
    out[#out + 1] = "{"
    local n = #v
    for i = 1, n do
      ser(v[i], skip, out)
      out[#out + 1] = ","
    end
    local keys = {}
    for k in pairs(v) do
      if not (type(k) == "number" and k >= 1 and k <= n and k % 1 == 0) and not (skip and skip[k]) then
        keys[#keys + 1] = k
      end
    end
    table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
    for _, k in ipairs(keys) do
      if type(k) == "string" and k:match("^[%a_][%w_]*$") and not KEYWORD[k] then out[#out + 1] = k .. "="
      else out[#out + 1] = "[" .. (type(k) == "string" and ("%q"):format(k) or num(k)) .. "]=" end
      ser(v[k], skip, out)
      out[#out + 1] = ","
    end
    out[#out + 1] = "}"
  else
    out[#out + 1] = "nil"
  end
end

-- the pane tree without its back links (parent, byName are rebuilt on load) and no words
local function stripText(p)
  if p.kind == "txt" or p.text ~= nil then p.text = "" end
  for _, c in ipairs(p.children or {}) do stripText(c) end
end

local SKIP = { parent = true, byName = true }

for i = 3, #arg do
  local pack = arg[i]
  local dir = inDir .. "/" .. pack
  local idx = readFile(dir .. "/index.lua")
  local names = idx and load(idx)() or {}
  table.sort(names)
  local out = { "-- generated by tools/lyt_data.lua: ", pack, "'s layouts and clips as numbers\n", "return {layouts={" }
  local nl, nc = 0, 0
  for _, name in ipairs(names) do
    if name:match("%.bclyt$") then
      local L = assert(F.layout(assert(readFile(dir .. "/" .. name))))
      stripText(L.root)
      out[#out + 1] = ("\n[%q]="):format(name)
      ser(L, SKIP, out)
      out[#out + 1] = ","
      nl = nl + 1
    end
  end
  out[#out + 1] = "},clips={"
  for _, name in ipairs(names) do
    if name:match("%.bclan$") then
      local C = assert(F.clip(assert(readFile(dir .. "/" .. name))))
      out[#out + 1] = ("\n[%q]="):format(name)
      ser(C, SKIP, out)
      out[#out + 1] = ","
      nc = nc + 1
    end
  end
  out[#out + 1] = "}}\n"
  local text = table.concat(out)
  local f = assert(io.open(outDir .. "/" .. pack .. ".lua", "wb"))
  f:write(text)
  f:close()
  print(("%s: %d layouts, %d clips, %d bytes"):format(pack, nl, nc, #text))
end
