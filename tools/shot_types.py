"""Build data/training_shot_types.lua from Bulbapedia's "List of Pokémon by Super Training
Energy Shot" article: the Energy Shot colour (black, yellow, orange, green, blue) of every
species, kept for National Dex 1..386 (the Gen 3 roster).

Usage:
  python tools/shot_types.py [--cache tools/_shot_types.wikitext] [--out data/training_shot_types.lua]

Derived from Bulbapedia (CC BY-NC-SA 2.5); keep the attribution line in the generated file
and in README.md.
"""

from __future__ import annotations

import os
import re
import sys
import urllib.request

API = ("https://bulbapedia.bulbagarden.net/w/api.php?action=parse"
       "&page=List_of_Pok%C3%A9mon_by_Super_Training_Energy_Shot&prop=wikitext&format=json&formatversion=2")
UA = "Mozilla/5.0 play_nav-shot-types/1.0 (gen1recomp mod tooling)"
COLOURS = ["black", "yellow", "orange", "green", "blue"]
MAX_NATIONAL = 386


def fetch(cache: str | None) -> str:
    if cache and os.path.exists(cache):
        with open(cache, encoding="utf-8") as f:
            return f.read()
    import json
    req = urllib.request.Request(API, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as resp:
        text = json.loads(resp.read().decode("utf-8"))["parse"]["wikitext"]
    if cache:
        with open(cache, "w", encoding="utf-8") as f:
            f.write(text)
    return text


def parse(wikitext: str) -> dict[int, str]:
    out: dict[int, str] = {}
    sections = re.split(r"^==\s*([A-Za-z]+)\s*==\s*$", wikitext, flags=re.M)
    # sections = [preamble, name1, body1, name2, body2, ...]
    for i in range(1, len(sections) - 1, 2):
        colour = sections[i].strip().lower()
        if colour not in COLOURS:
            continue
        for m in re.finditer(r"\{\{MSP/6\|(\d+)[A-Za-z]*\|", sections[i + 1]):
            n = int(m.group(1))
            if 1 <= n <= MAX_NATIONAL and n not in out:
                out[n] = colour
    return out


def main(argv: list[str]) -> int:
    cache = argv[argv.index("--cache") + 1] if "--cache" in argv else None
    out_path = argv[argv.index("--out") + 1] if "--out" in argv else "data/training_shot_types.lua"
    table = parse(fetch(cache))
    counts = {c: sum(1 for v in table.values() if v == c) for c in COLOURS}
    missing = [n for n in range(1, MAX_NATIONAL + 1) if n not in table]
    lines = [
        "-- Super Training Energy Shot colour by National Dex number (1..386), generated by",
        "-- tools/shot_types.py from Bulbapedia, \"List of Pokemon by Super Training Energy Shot\"",
        "-- (CC BY-NC-SA 2.5). black average, yellow rapid-fire, orange big, green slow and",
        "-- strong, blue fast and small. Species absent from the list fall back by type in",
        "-- src/training/rules.lua. Counts: %s; missing: %s" % (
            ", ".join("%s %d" % (c, counts[c]) for c in COLOURS), missing or "none"),
        "",
        "return {",
    ]
    for n in sorted(table):
        lines.append("  [%d] = %q," % (n, table[n]) if False else '  [%d] = "%s",' % (n, table[n]))
    lines.append("}")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s: %d species, %s, missing %s" % (out_path, len(table), counts, missing))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
