"""Bake Pokemon-Amie's Poke Puffs into one indexed atlas (Wilds of Hoenn's colour-number trick,
as tools/decor_atlas.py).

The 26 puffs come from a page provided via The Spriters Resource ("Pokemon-Amie - Poke Puffs";
attribution in assets/credits.txt): a teal grid of cells, each puff's 40x40 texture at
the cell's top left. CELLS below says which cell holds which puff. Each sprite is stored as
COLOUR NUMBERS: 0 transparent, 1..n an entry of that sprite's own palette. Out:
  assets/amie_puffs.png   one greyscale image, the puffs in rows; grey = number
  data/amie_puffs.lua     { cells = { [id] = { x, y, w, h, pal } } }, pal = "rrggbbaa" strings
src/amie/decor_art.lua expands a cell into a full-colour image the first time it is drawn.

  python tools/puff_atlas.py "<...Pokemon-Amie - Poke Puffs.png>"
"""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SIZE = 40
PER_ROW = 6

# the page's cells (their top-left corners) and the puff each holds
CELLS = [
    (2, 2, "puff/sweet_basic"),
    (68, 2, "puff/sweet_frosted"),
    (134, 2, "puff/sweet_fancy"),
    (200, 2, "puff/sweet_deluxe"),
    (2, 68, "puff/mint_basic"),
    (68, 68, "puff/mint_frosted"),
    (134, 68, "puff/mint_fancy"),
    (200, 68, "puff/mint_deluxe"),
    (2, 134, "puff/citrus_basic"),
    (68, 134, "puff/citrus_frosted"),
    (134, 134, "puff/citrus_fancy"),
    (200, 134, "puff/citrus_deluxe"),
    (2, 200, "puff/mocha_basic"),
    (68, 200, "puff/mocha_frosted"),
    (134, 200, "puff/mocha_fancy"),
    (200, 200, "puff/mocha_deluxe"),
    (2, 266, "puff/spice_basic"),
    (68, 266, "puff/spice_frosted"),
    (134, 266, "puff/spice_fancy"),
    (200, 266, "puff/spice_deluxe"),
    (2, 332, "puff/supreme_wish"),
    (68, 332, "puff/supreme_honor"),
    (134, 332, "puff/supreme_spring"),
    (200, 332, "puff/supreme_summer"),
    (266, 332, "puff/supreme_fall"),
    (332, 332, "puff/supreme_winter"),
]


def unrip(im):
    """The page's 4-bit channels back to the game's levels: it expanded a 4-bit value n as
    n * 16 (white 240, opaque 240) where the game uses n * 17. A sprite whose every channel
    value is a multiple of 16 is such a texture throughout; one whose alpha alone is (a 4-bit
    alpha over full colour) has only its alpha put back."""
    px = list(im.getdata())
    seen = [p for p in px if p[3] > 0]
    def x16(vals): return all(v % 16 == 0 for v in vals)
    rgb = x16(c for p in seen for c in p[:3])
    alpha = x16(p[3] for p in seen)
    if not (rgb or alpha):
        return im
    up = lambda v: v + v // 16
    out = []
    for p in px:
        if p[3] == 0:
            out.append(p)
        elif rgb:
            out.append((up(p[0]), up(p[1]), up(p[2]), up(p[3]) if alpha else p[3]))
        else:
            out.append((p[0], p[1], p[2], up(p[3])))
    im = im.copy()
    im.putdata(out)
    return im


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    page = Image.open(sys.argv[1]).convert("RGBA")
    rows_n = (len(CELLS) + PER_ROW - 1) // PER_ROW
    atlas = Image.new("L", (SIZE * PER_ROW, SIZE * rows_n), 0)
    rows = []
    for i, (cx, cy, id_) in enumerate(CELLS):
        px = unrip(page.crop((cx, cy, cx + SIZE, cy + SIZE))).load()
        ax, ay = (i % PER_ROW) * SIZE, (i // PER_ROW) * SIZE
        pal, index = [], {}
        for yy in range(SIZE):
            for xx in range(SIZE):
                p = px[xx, yy]
                if p[3] == 0:
                    continue
                if p not in index:
                    pal.append(p)
                    index[p] = len(pal)
                    if len(pal) > 255:
                        sys.exit(f"{id_}: more than 255 colours")
                atlas.putpixel((ax + xx, ay + yy), index[p])
        rows.append((id_, ax, ay, pal))

    png = os.path.join(ROOT, "assets", "amie_puffs.png")
    atlas.save(png, optimize=True)
    lines = [
        "-- generated by tools/puff_atlas.py: Pokemon-Amie's Poke Puffs in assets/amie_puffs.png",
        "-- (grey value = colour number, 0 transparent) and their palettes. Art: see assets/credits.txt",
        "-- (Poke Puffs).",
        "return {",
        "  cells = {",
    ]
    for id_, ax, ay, pal in sorted(rows):
        hexes = ", ".join('"%02x%02x%02x%02x"' % p for p in pal)
        lines.append(f'    ["{id_}"] = {{ x = {ax}, y = {ay}, w = {SIZE}, h = {SIZE}, pal = {{ {hexes} }} }},')
    lines += ["  },", "}", ""]
    with open(os.path.join(ROOT, "data", "amie_puffs.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(rows)} puffs; {png} {atlas.size} {os.path.getsize(png)} bytes")


if __name__ == "__main__":
    main()
