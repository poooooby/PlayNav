-- Pokemon Alpha Sapphire (USA) Rev 2: which textures Pokemon-Amie takes
-- from the player's own card image, by archive / entry / sub-entry / CLIM
-- index inside the (LZ11-decompressed) entry. Produced from the contact
-- sheets of tools/discover.py; the mod ships this table only, never pixels.
--
-- `clim` is the 0-based index of the CLIM inside the entry blob (entries in
-- these archives are packs holding many textures). `w`/`h`/`fmt` are
-- checked after decoding so a wrong index is caught and reported, not drawn.

local A = {}
local function add(archive, entry, sub, clim, id, w, h, fmt, note)
  A[#A + 1] = { archive = archive, entry = entry, sub = sub, clim = clim,
    id = id, w = w, h = h, fmt = fmt, note = note }
end

